forecast.loc[0, 'yhat_lower'] = gdp_country[' Gross Domestic Product (GDP) '].iloc[-1]
forecast.loc[0, 'yhat_upper'] = gdp_country[' Gross Domestic Product (GDP) '].iloc[-1]

# ----------------- Función para graficar -----------------
def plot_gdp_with_forecast(gdp_data, forecast, title, x_start=None):
    plt.figure(figsize=(12, 6))

    # Línea histórica
    plt.plot(
        gdp_data[' Year '],
        gdp_data[' Gross Domestic Product (GDP) '] / 1_000_000_000,
        marker='o',
        label='Historical'
    )

    # Línea de predicción (desde último punto histórico)
    forecast_years = forecast['ds'].dt.year
    plt.plot(
        forecast_years,
        forecast['yhat'] / 1_000_000_000,
        color='#0D47A1',  # Azul oscuro
        label='Forecast'
    )

    # Sombreado probabilístico (80% intervalo)
    plt.fill_between(
        forecast_years,
        forecast['yhat_lower'] / 1_000_000_000,
        forecast['yhat_upper'] / 1_000_000_000,
        color='#82B1FF',  # Azul claro
        alpha=0.3,
        label='80% Confidence Interval'
    )

    # Líneas punteadas horizontales representando GDP cada 5 años y último año
    y_max = max(gdp_data[' Gross Domestic Product (GDP) ']/1_000_000_000) * 1.05  # Para ajustar posición texto
    x_min = x_start if x_start is not None else gdp_data[' Year '].min()
    x_max = forecast_years.max()

    for year, y in zip(forecast_years, forecast['yhat']):
        if (year - last_year) % 5 == 0 or year == forecast_years.iloc[-1]:
            y_billions = y / 1_000_000_000
            # Línea horizontal completa
            plt.hlines(y=y_billions, xmin=x_min, xmax=x_max, colors='black', linestyles='--', linewidth=1)
            # Texto centrado sobre la línea
            plt.text((x_min + x_max)/2, y_billions + y_max*0.01,
                     f'{y_billions:.4f}', ha='center', va='bottom', fontsize=10, fontweight='bold')

    # Formato gráfico
    plt.title(title)
    plt.xlabel('Year')
    plt.ylabel('GDP (Billion USD)')

    # Eje x
    plt.xlim(x_min, x_max)
    plt.xticks(np.arange(x_min, x_max + 1, 5))

    plt.ticklabel_format(style='plain', axis='y')
    plt.grid(True)
    plt.legend()
    plt.show()

